<template>
  <div v-if="isOne && isMatchType" class="attr-item-box">
    <div class="flex-view">
      <div class="flex-item">
        <span class="label">数据字段</span>
        <div class="content">
          <Input v-model="baseAttr._field_" @on-change="changeCommon" />
        </div>
      </div>
    </div>
  </div>
</template>

<script name="Price" setup>
import useSelect from '@/hooks/select';

const baseAttr = reactive({
  _field_: '',
});

const matchType = ['textbox', 'i-text', 'barcode', 'qrcode'];
const { isMatchType, canvasEditor, isOne } = useSelect(matchType);

const getObjectAttr = (e) => {
  const activeObject = canvasEditor.canvas.getActiveObject();
  // 不是当前obj，跳过
  if (e && e.target && e.target !== activeObject) return;
  if (activeObject && isMatchType) {
    baseAttr._field_ = activeObject.get('extension')?._field_ || '';
  }
};

const changeCommon = () => {
  const activeObject = canvasEditor.canvas.getActiveObjects()[0];
  const extension = activeObject?.get('extension') || {}
  if (extension) {
    extension._field_ = baseAttr._field_
    activeObject.set('extension', extension);
  }
};

const update = getCurrentInstance();
const selectCancel = () => {
  update?.proxy?.$forceUpdate();
};

onMounted(() => {
  // 获取字体数据
  getObjectAttr();
  canvasEditor.on('selectCancel', selectCancel);
  canvasEditor.on('selectOne', getObjectAttr);
  canvasEditor.canvas.on('object:modified', getObjectAttr);
});

onBeforeUnmount(() => {
  canvasEditor.off('selectCancel', selectCancel);
  canvasEditor.off('selectOne', getObjectAttr);
  canvasEditor.canvas.off('object:modified', getObjectAttr);
});
</script>

